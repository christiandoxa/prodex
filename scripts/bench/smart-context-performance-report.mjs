#!/usr/bin/env node
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { repoRoot } from "../npm/common.mjs";
import { runChecked } from "../lib/checked-subprocess.mjs";

const criterionRoot = path.join(repoRoot, "target", "criterion");
const outputRoot = path.join(repoRoot, "docs", "generated");
const command = "cargo bench --locked --features bench-support --bench runtime_proxy_hot_paths -- runtime_smart_context_ --noplot --warm-up-time 1 --measurement-time 2 --sample-size 50";

function quantile(sorted, proportion) {
  return sorted[Math.ceil(sorted.length * proportion) - 1];
}

function benchmark(name) {
  const root = path.join(criterionRoot, name, "new");
  const sample = JSON.parse(fs.readFileSync(path.join(root, "sample.json"), "utf8"));
  const estimates = JSON.parse(fs.readFileSync(path.join(root, "estimates.json"), "utf8"));
  const samples = sample.times.map((time, index) => time / sample.iters[index]);
  const sorted = [...samples].sort((left, right) => left - right);
  const mean = samples.reduce((sum, value) => sum + value, 0) / samples.length;
  const variance = samples.reduce((sum, value) => sum + (value - mean) ** 2, 0) / samples.length;
  return {
    name,
    sample_count: samples.length,
    p50_ns: quantile(sorted, 0.5),
    p95_ns: quantile(sorted, 0.95),
    p99_ns: quantile(sorted, 0.99),
    mean_ns: mean,
    standard_deviation_ns: Math.sqrt(variance),
    coefficient_of_variation: mean === 0 ? 0 : Math.sqrt(variance) / mean,
    criterion_median_estimate_ns: estimates.median.point_estimate,
    samples_ns: samples,
  };
}

function formatDuration(ns) {
  if (ns >= 1_000_000) return `${(ns / 1_000_000).toFixed(3)} ms`;
  if (ns >= 1_000) return `${(ns / 1_000).toFixed(3)} us`;
  return `${ns.toFixed(2)} ns`;
}

const names = fs
  .readdirSync(criterionRoot)
  .filter((name) => name.startsWith("runtime_smart_context_"))
  .filter((name) => fs.existsSync(path.join(criterionRoot, name, "new", "sample.json")))
  .sort();
const benchmarks = names.map(benchmark);
if (benchmarks.some((value) => value.sample_count !== 50)) {
  throw new Error(`expected 50 samples from: ${command}`);
}

const cargoLock = fs.readFileSync(path.join(repoRoot, "Cargo.lock"), "utf8");
const criterionVersion = cargoLock.match(/name = "criterion"\nversion = "([^"]+)"/u)?.[1] ?? "unknown";
const report = {
  schema_version: 1,
  evidence_level: "machine_specific_deterministic_performance",
  provenance: {
    commit_sha: runChecked("git", ["rev-parse", "HEAD"], { cwd: repoRoot }).stdout.trim(),
    rust_toolchain: runChecked("rustc", ["--version"], { cwd: repoRoot }).stdout.trim(),
    criterion_version: criterionVersion,
    os: `${os.platform()} ${os.release()}`,
    architecture: os.arch(),
    cpu: os.cpus()[0]?.model ?? "unknown",
    logical_cpus: os.cpus().length,
    memory_bytes: os.totalmem(),
    command,
  },
  benchmarks,
};

const lines = [
  "<!-- generated by scripts/bench/smart-context-performance-report.mjs; do not edit -->",
  "# Smart Context Performance Report",
  "",
  `- source_commit: ${report.provenance.commit_sha}`,
  `- rust_toolchain: ${report.provenance.rust_toolchain}`,
  `- host: ${report.provenance.cpu}; ${report.provenance.logical_cpus} logical CPUs`,
  `- command: \`${command}\``,
  "- samples: 50 per case",
  "",
  "| Case | p50 | p95 | p99 | CV |",
  "| --- | ---: | ---: | ---: | ---: |",
];
for (const value of benchmarks) {
  lines.push(`| ${value.name} | ${formatDuration(value.p50_ns)} | ${formatDuration(value.p95_ns)} | ${formatDuration(value.p99_ns)} | ${(value.coefficient_of_variation * 100).toFixed(2)}% |`);
}
lines.push("", "These machine-specific measurements do not prove live-model quality or allocation behavior.", "");

fs.mkdirSync(outputRoot, { recursive: true });
fs.writeFileSync(path.join(outputRoot, "smart-context-performance-report.json"), `${JSON.stringify(report, null, 2)}\n`);
fs.writeFileSync(path.join(outputRoot, "smart-context-performance-report.md"), lines.join("\n"));
process.stdout.write("Smart Context performance report generated\n");
