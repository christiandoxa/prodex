#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { repoRoot } from "../npm/common.mjs";
import { runChecked, runCheckedJson } from "../lib/checked-subprocess.mjs";

const write = process.argv.includes("--write");
const check = process.argv.includes("--check");
if (write === check) {
  throw new Error("pass exactly one of --write or --check");
}

const corpus = "crates/prodex-runtime-proxy/tests/fixtures/smart_context_replay_corpus.json";
const outputRoot = path.join(repoRoot, "docs", "generated");
const jsonPath = path.join(outputRoot, "smart-context-replay-report.json");
const markdownPath = path.join(outputRoot, "smart-context-replay-report.md");
const commit = runChecked("git", ["rev-parse", "HEAD"], { cwd: repoRoot }).stdout.trim();
const rustToolchain = runChecked("rustc", ["--version"], { cwd: repoRoot }).stdout.trim();
const report = runCheckedJson(
  "cargo",
  ["run", "--locked", "-q", "--features", "allocation-bench-support", "--bin", "prodex", "--", "context", "replay-report", corpus, "--json", "--strict"],
  {
    cwd: repoRoot,
    timeoutMs: 600_000,
    maxOutputBytes: 16 * 1024 * 1024,
    env: { ...process.env, PRODEX_GIT_COMMIT: commit, PRODEX_RUST_TOOLCHAIN: rustToolchain },
  },
);

function renderMarkdown(value) {
  const lines = [
    "<!-- generated by scripts/docs/smart-context-evidence.mjs; do not edit -->",
    "# Smart Context Deterministic Replay",
    "",
    `- source_commit: ${value.provenance.commit_sha ?? "unknown"}`,
    `- rust_toolchain: ${value.provenance.rust_toolchain ?? "unknown"}`,
    `- environment: ${value.provenance.os}/${value.provenance.architecture}`,
    `- tokenizer: ${value.provenance.tokenizer_source}`,
    `- token_measurement: ${value.provenance.token_measurement}`,
    `- scenarios: ${value.scenarios.length}`,
    `- exact_input_tokens: ${value.exact_input_tokens}`,
    `- optimized_input_tokens: ${value.optimized_input_tokens}`,
    `- net_saved_tokens: ${value.net_saved_tokens}`,
    `- passed: ${value.passed}`,
    "",
    "| Scenario | Route | Mode | Turns | Net tokens | Result |",
    "| --- | --- | --- | ---: | ---: | --- |",
  ];
  for (const scenario of value.scenarios) {
    lines.push(
      `| ${scenario.id} | ${scenario.route}/${scenario.transport} | ${scenario.mode} | ${scenario.turns.length} | ${scenario.net_saved_tokens} | ${scenario.passed ? "pass" : "fail"} |`,
    );
  }
  lines.push("");
  lines.push("This is deterministic correctness, tokenizer-count, and optimized-rewrite allocation evidence. It is not live-model quality evidence.");
  lines.push("");
  return lines.join("\n");
}

function normalizedReport(value) {
  const normalized = structuredClone(value);
  normalized.provenance.package_version = "<package-version>";
  normalized.provenance.commit_sha = "<source-commit>";
  normalized.provenance.rust_toolchain = "<toolchain>";
  for (const scenario of normalized.scenarios) {
    for (const turn of scenario.turns) {
      turn.rewrite_duration_ns = 0;
      if (turn.allocation_bytes !== null) turn.allocation_bytes = 0;
    }
  }
  return JSON.stringify(normalized);
}

function normalizedMarkdown(value) {
  return value
    .replace(/^- source_commit: .*$/mu, "- source_commit: <source-commit>")
    .replace(/^- rust_toolchain: .*$/mu, "- rust_toolchain: <toolchain>");
}

const json = `${JSON.stringify(report, null, 2)}\n`;
const markdown = renderMarkdown(report);
if (write) {
  fs.mkdirSync(outputRoot, { recursive: true });
  fs.writeFileSync(jsonPath, json);
  fs.writeFileSync(markdownPath, markdown);
  process.stdout.write("Smart Context evidence generated\n");
} else {
  const checkedJson = JSON.parse(fs.readFileSync(jsonPath, "utf8"));
  const checkedMarkdown = fs.readFileSync(markdownPath, "utf8");
  if (normalizedReport(checkedJson) !== normalizedReport(report)) {
    throw new Error("Smart Context replay JSON is stale; run npm run docs:smart-context-evidence");
  }
  if (normalizedMarkdown(checkedMarkdown) !== normalizedMarkdown(renderMarkdown(report))) {
    throw new Error("Smart Context replay Markdown is stale; run npm run docs:smart-context-evidence");
  }
  process.stdout.write("Smart Context evidence: ok\n");
}
